import { Bluetooth, Zap, Calendar, Settings, Cpu, Trash2 } from 'lucide-react';
import { useAppStore } from '../store/appStore';
import type { ActivityEvent, ActivityCategory } from '../models/types';
import { formatDistanceToNow } from 'date-fns';

const CATEGORY_ICONS: Record<ActivityCategory, React.ElementType> = {
  bluetooth: Bluetooth,
  device: Zap,
  schedule: Calendar,
  system: Settings,
};

export default function ActivityPage() {
  const activity = useAppStore((s) => s.activity);
  const clearActivity = useAppStore((s) => s.clearActivity);

  return (
    <div>
      <div className="page-header">
        <div className="flex items-center justify-between gap-4">
          <div>
            <h2>Activity</h2>
            <p>{activity.length} event{activity.length !== 1 ? 's' : ''} recorded</p>
          </div>
          {activity.length > 0 && (
            <button className="btn btn-secondary btn-sm" onClick={clearActivity}>
              <Trash2 size={14} /> Clear All
            </button>
          )}
        </div>
      </div>

      {/* Legend */}
      <div className="card mb-6" style={{ padding: 'var(--space-4)' }}>
        <p style={{ fontSize: 'var(--text-xs)', color: 'var(--color-text-secondary)' }}>
          Events marked <strong>HW</strong> are confirmed by hardware. All others are UI-only events generated by the app.
        </p>
      </div>

      {activity.length === 0 ? (
        <div className="empty-state">
          <Cpu size={48} />
          <p>No activity yet. Connect Bluetooth or interact with devices to see events here.</p>
        </div>
      ) : (
        <div className="card" style={{ padding: 'var(--space-5)' }}>
          {activity.map((event) => (
            <ActivityItem key={event.id} event={event} />
          ))}
        </div>
      )}
    </div>
  );
}

function ActivityItem({ event }: { event: ActivityEvent }) {
  const Icon = CATEGORY_ICONS[event.category];
  const timeAgo = formatDistanceToNow(new Date(event.timestamp), { addSuffix: true });
  const exactTime = new Date(event.timestamp).toLocaleTimeString();

  return (
    <div className="activity-item">
      <div className={`activity-icon ${event.level}`}>
        <Icon size={15} aria-hidden="true" />
      </div>
      <div className="activity-content" style={{ flex: 1, minWidth: 0 }}>
        <div className="flex items-center gap-2" style={{ flexWrap: 'wrap' }}>
          <span className="title">{event.title}</span>
          {event.isHardwareConfirmed && (
            <span className="badge badge-connected" style={{ fontSize: '0.65rem' }}>HW</span>
          )}
        </div>
        {event.detail && (
          <div className="meta">{event.detail}</div>
        )}
        <div className="meta" title={exactTime}>{timeAgo}</div>
      </div>
    </div>
  );
}
